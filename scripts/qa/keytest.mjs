import { chromium } from "playwright"; import { BASE, sleep } from "./lib.mjs";
const b = await chromium.launch(); const ctx = await b.newContext({ viewport:{width:412,height:915}});
await ctx.addInitScript(`localStorage.setItem("apex.onboarded","1")`);
const p = await ctx.newPage(); const errs=[]; p.on("pageerror",e=>errs.push(e.message));
await p.goto(`${BASE}/app/`); await sleep(2000);
await p.getByRole("button",{name:/Open sidebar/}).first().click(); await sleep(600);
await p.getByRole("navigation",{name:"Workspace"}).getByRole("button",{name:/Settings/}).click(); await sleep(800);
await p.getByRole("button",{name:/Enter key/}).click(); await sleep(600);
console.log((await p.locator("input").evaluateAll(l=>l.map(i=>i.placeholder||i.ariaLabel))).join("|"));
await p.screenshot({path:"/tmp/qa/k0.png"}); await p.locator("input:visible, textarea:visible").last().fill("APEX-PRO-2025");
await p.keyboard.press("Enter"); await sleep(6000);
console.log((await p.innerText("body")).slice(0,400).replace(/\n/g," | "));
await p.screenshot({path:"/tmp/qa/keyflow.png"}); console.log("errs",errs);
await b.close();
